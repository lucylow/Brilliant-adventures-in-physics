export function catalogByConcept(conceptId: string): CatalogTopic[] {
  return CATALOG.filter((topic) => topic.conceptId === conceptId);
}

export function catalogTopic(id: string): CatalogTopic | undefined {
  return CATALOG.find((topic) => topic.id === id);
}

export function catalogForIndex(index: number): CatalogTopic {
  return CATALOG[((index % CATALOG.length) + CATALOG.length) % CATALOG.length];
}

export function allCatalogConceptIds(): string[] {
  return [...new Set(CATALOG.map((topic) => topic.conceptId))];
}

export function assertCatalogReferences(): void {
  for (const topic of CATALOG) {
    requireConcept(topic.conceptId);
  }
  for (const concept of conceptRegistry) {
    if (!CATALOG.some((topic) => topic.conceptId === concept.id)) {
      throw new Error(`Concept ${concept.id} is missing from the AI catalog`);
    }
  }
}

export const EXPLAIN_VARIANTS = ["kid-friendly", "beginner", "standard", "advanced", "exam-review", "intuition-first", "mathematical"] as const;

export function explanationText(topic: CatalogTopic, variant: (typeof EXPLAIN_VARIANTS)[number]): string {
  switch (variant) {
    case "kid-friendly":
      return topic.kidFriendly;
    case "beginner":
      return topic.beginner;
    case "standard":
      return topic.standard;
    case "advanced":
      return topic.advanced;
    case "exam-review":
      return topic.examReview;
    case "intuition-first":
      return topic.intuitionFirst;
    case "mathematical":
      return topic.mathematical;
    default:
      return topic.standard;
  }
}

export function levelForVariant(variant: (typeof EXPLAIN_VARIANTS)[number]): EducationLevel | "kid-friendly" {
  if (variant === "kid-friendly") return "kid-friendly";
  if (variant === "beginner" || variant === "intuition-first") return "middle-school";
  if (variant === "advanced" || variant === "mathematical") return "advanced";
  if (variant === "exam-review") return "high-school";
  return "high-school";
}
